// Drive the real app in Chromium and take screenshots of the main screens.
//   node tests/harness/ui.mjs [outdir]
import { chromium } from '@playwright/test';
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const out = process.argv[2] || path.join(root, 'shots');
fs.mkdirSync(out, { recursive: true });
const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.png': 'image/png', '.json': 'application/json' };
const srv = http.createServer((req, res) => {
  let p = path.join(root, decodeURIComponent(req.url.split('?')[0]));
  if (p.endsWith('/')) p += 'index.html';
  fs.readFile(p, (e, d) => { if (e) { res.writeHead(404); res.end(); return; } res.writeHead(200, { 'content-type': types[path.extname(p)] || 'application/octet-stream' }); res.end(d); });
}).listen(0);
const port = srv.address().port;
const W = +(process.env.W || 1600), H = +(process.env.H || 900);
const b = await chromium.launch();
const pg = await b.newPage({ viewport: { width: W, height: H } });
const errors = [];
pg.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
pg.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
await pg.route(/fonts\.(googleapis|gstatic)\.com/, (r) => r.abort());
const shot = async (name) => { await pg.screenshot({ path: path.join(out, name + '.png') }); console.log('shot', name); };
await pg.goto(`http://localhost:${port}/index.html`);
await pg.waitForTimeout(2500);
await shot('ui-title');
await pg.getByText('开始战役').click();
await pg.waitForTimeout(800);
await shot('ui-campaign');
await pg.locator('button.lvl').first().click();
await pg.waitForTimeout(1500);
await shot('ui-brief');
await pg.getByText('交给 AI').click();
await pg.waitForTimeout(9000);
await shot('ui-game');
await pg.keyboard.press('t');
await pg.waitForTimeout(600);
await shot('ui-tech');
await pg.keyboard.press('Escape');
await pg.keyboard.press('c');
await pg.waitForTimeout(1500);
await shot('ui-codex');
await pg.keyboard.press('Escape');
await pg.keyboard.press('5');
await pg.waitForTimeout(12000);
await shot('ui-game2');
console.log('errors:', errors.length ? errors.slice(0, 10).join('\n') : 'none');
await b.close(); srv.close();
