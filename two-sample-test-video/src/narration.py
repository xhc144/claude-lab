_REPL = [
    ("σ₁", "西格玛一"), ("σ₂", "西格玛二"), ("σ", "西格玛"),
    ("n−1", "n减1"), ("0-1", "零一"), ("……", "，"),
    ("52.5%", "百分之五十二点五"), ("65%", "百分之六十五"), ("40%", "百分之四十"),
    ("“", ""), ("”", ""), ("Welch", "韦尔奇"),
]


def spoken(text):
    for a, b in _REPL:
        text = text.replace(a, b)
    return text.replace(" ", "")


