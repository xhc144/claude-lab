#!/usr/bin/env node
// Generates bundled design assets from npm packages:
//   dist/fonts/**            woff2 files + fonts.css (unicode-range subsets, loaded on demand)
//   src/generated/fonts.json font manifest (families, files, ranges) used by HTML export subsetting
//   src/generated/icons.json Lucide icons converted to compact SVG path data (Path2D friendly)
//   src/generated/world.json world-atlas 110m countries TopoJSON (for globe / map components)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const nm = path.join(root, 'node_modules');
const genDir = path.join(root, 'src/generated');
const fontOut = path.join(root, 'dist/fonts');
fs.mkdirSync(genDir, { recursive: true });
fs.mkdirSync(fontOut, { recursive: true });

// family name used by the engine → source css files. Subsets we do not need are skipped.
const FONTS = [
  { family: 'Motif Inter', dir: 'inter', css: ['@fontsource-variable/inter/wght.css', '@fontsource-variable/inter/wght-italic.css'] },
  { family: 'Motif Grotesk', dir: 'grotesk', css: ['@fontsource-variable/space-grotesk/wght.css'] },
  { family: 'Motif Archivo', dir: 'archivo', css: ['@fontsource-variable/archivo/standard.css', '@fontsource-variable/archivo/standard-italic.css'] },
  { family: 'Motif Fraunces', dir: 'fraunces', css: ['@fontsource-variable/fraunces/standard.css', '@fontsource-variable/fraunces/standard-italic.css'] },
  { family: 'Motif Outfit', dir: 'outfit', css: ['@fontsource-variable/outfit/wght.css'] },
  { family: 'Motif Mono', dir: 'mono', css: ['@fontsource-variable/jetbrains-mono/wght.css', '@fontsource-variable/jetbrains-mono/wght-italic.css'] },
  { family: 'Motif Instrument', dir: 'instrument', css: ['@fontsource/instrument-serif/400.css', '@fontsource/instrument-serif/400-italic.css'] },
  { family: 'Motif Sans SC', dir: 'sans-sc', css: ['@fontsource-variable/noto-sans-sc/wght.css'] },
  { family: 'Motif Serif SC', dir: 'serif-sc', css: ['@fontsource-variable/noto-serif-sc/wght.css'] },
  { family: 'Motif Brush SC', dir: 'brush-sc', css: ['@fontsource/ma-shan-zheng/400.css'] },
];
const SKIP = /cyrillic|vietnamese/;

function genFonts() {
  let css = '/* generated by scripts/gen-assets.mjs — OFL fonts from @fontsource */\n';
  const manifest = {};
  let bytes = 0;
  for (const f of FONTS) {
    const dest = path.join(fontOut, f.dir);
    fs.mkdirSync(dest, { recursive: true });
    manifest[f.family] = { dir: f.dir, faces: [] };
    for (const rel of f.css) {
      const file = path.join(nm, rel);
      const text = fs.readFileSync(file, 'utf8');
      for (const m of text.matchAll(/\/\*\s*([^*]+?)\s*\*\/\s*@font-face\s*{([^}]*)}/g)) {
        const [, label, body] = m;
        if (SKIP.test(label) && !/noto-s/.test(label)) continue;
        const src = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(body)?.[1];
        if (!src) continue;
        const style = /font-style:\s*([^;]+);/.exec(body)?.[1] || 'normal';
        const weight = /font-weight:\s*([^;]+);/.exec(body)?.[1] || '400';
        const stretch = /font-stretch:\s*([^;]+);/.exec(body)?.[1];
        const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1];
        fs.copyFileSync(path.join(path.dirname(file), 'files', src), path.join(dest, src));
        bytes += fs.statSync(path.join(dest, src)).size;
        css += `@font-face{font-family:'${f.family}';font-style:${style};font-display:block;font-weight:${weight};${stretch ? `font-stretch:${stretch};` : ''}src:url(./${f.dir}/${src}) format('woff2');${range ? `unicode-range:${range};` : ''}}\n`;
        manifest[f.family].faces.push({ file: `${f.dir}/${src}`, style, weight, stretch: stretch || null, range: range || null });
      }
    }
  }
  fs.writeFileSync(path.join(fontOut, 'fonts.css'), css);
  fs.writeFileSync(path.join(genDir, 'fonts.json'), JSON.stringify(manifest));
  console.log(`fonts: ${FONTS.length} families, ${(bytes / 1048576).toFixed(1)} MB`);
}

// ---- icons ---------------------------------------------------------------
const n = (v) => Number(v);
function nodeToPath([tag, a]) {
  switch (tag) {
    case 'path': return a.d;
    case 'circle': {
      const cx = n(a.cx), cy = n(a.cy), r = n(a.r);
      return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0z`;
    }
    case 'ellipse': {
      const cx = n(a.cx), cy = n(a.cy), rx = n(a.rx), ry = n(a.ry);
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0z`;
    }
    case 'rect': {
      const x = n(a.x || 0), y = n(a.y || 0), w = n(a.width), h = n(a.height);
      const r = Math.min(n(a.rx || a.ry || 0), w / 2, h / 2);
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}z`;
      return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}z`;
    }
    case 'line': return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case 'polyline': return 'M' + a.points.trim().split(/[\s,]+/).reduce((acc, v, i) => acc + (i % 2 ? ' ' + v : (i ? 'L' : '') + v), '');
    case 'polygon': return 'M' + a.points.trim().split(/[\s,]+/).reduce((acc, v, i) => acc + (i % 2 ? ' ' + v : (i ? 'L' : '') + v), '') + 'z';
    default: return null;
  }
}

async function genIcons() {
  const dir = path.join(nm, 'lucide/dist/esm/icons');
  const out = {};
  for (const file of fs.readdirSync(dir)) {
    if (!file.endsWith('.mjs')) continue;
    const mod = await import(pathToFileURL(path.join(dir, file)).href);
    const parts = mod.default.map(nodeToPath).filter(Boolean);
    out[file.replace(/\.mjs$/, '')] = parts.join('|');
  }
  fs.writeFileSync(path.join(genDir, 'icons.json'), JSON.stringify(out));
  console.log(`icons: ${Object.keys(out).length} lucide icons`);
}

function genWorld() {
  const src = path.join(nm, 'world-atlas/countries-110m.json');
  fs.copyFileSync(src, path.join(genDir, 'world.json'));
  console.log('world: countries-110m topojson');
}

genFonts();
await genIcons();
genWorld();
