def all_lines():
    for scene, lines in LINES.items():
        for item in lines:
            key, sub = item[0], item[1]
            say = item[2] if len(item) > 2 else sub
            yield scene, key, sub, say


_CUT = re.compile(r"[，；：。？！]")

if __name__ == "__main__":
    keys, bad = set(), 0
    for scene, key, sub, say in all_lines():
        assert key not in keys, key
        keys.add(key)
        if _CUT.findall(sub) != _CUT.findall(say):
            bad += 1
            print(f"句读不一致 {key}\n  字幕：{sub}\n  配音：{say}")
        if re.search(r"[α-ωΑ-Ω₀-₉ᵢₙ²³⁷√±≤≠≈∝∪∩∅⊥̂̄̃]", say):
            bad += 1
            print(f"配音文字里还有记号 {key}：{say}")
    n = sum(len(s[3]) for s in all_lines())
    print(f"{len(keys)} 句，配音约 {n} 字，估计 {n / 4.4 / 60:.1f} 分钟；问题 {bad} 处")
