// Drives the real UI in headless Chromium (software WebGL) and saves screenshots.
import { chromium } from 'playwright-core';
import { createServer } from 'vite';
import fs from 'node:fs';
const out = 'test-output/ui';
fs.mkdirSync(out, { recursive: true });
const W = Number(process.env.W || 1440), H = Number(process.env.H || 810);
const server = await createServer({ configFile: 'vite.config.mjs', server: { port: 5199 }, logLevel: 'error' });
await server.listen();
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: W, height: H } });
const logs = [];
page.on('console', (m) => { const t = m.type(); if (t === 'error' || t === 'warning') { logs.push(`[${t}] ${m.text()}`); console.log('[console]', t, m.text().slice(0, 600)); } });
page.on('pageerror', (e) => { logs.push('[pageerror] ' + e.message); console.log('[pageerror]', e.message); });
const shot = async (name) => { await page.screenshot({ path: `${out}/${name}.png`, timeout: 120000 }); console.log('shot', name); };
const step = async (ms) => { await page.mouse.move(700 + Math.random() * 20, 300 + Math.random() * 20); await page.waitForTimeout(ms); };
await page.goto('http://localhost:5199/index.html');
await page.waitForFunction(() => window.__app && window.__app.running, null, { timeout: 120000 });
await step(5000);
await shot('01-welcome');
await page.click('text=播放内置演示曲');
await page.waitForFunction(() => window.__app.track && window.__app.audio.playing, null, { timeout: 240000 });
console.log('analysis', await page.evaluate(() => { const a = window.__app.track.analysis; return JSON.stringify({ bpm: a.bpm, conf: a.tempoConf, beats: a.beats.length, downbeats: a.downbeats.length, drops: Array.from(a.drops), sections: Array.from(a.sections), kicks: a.kicks.length / 2, snares: a.snares.length / 2, hats: a.hats.length / 2, dur: a.duration }); }));
await page.evaluate(() => window.__app.seek(44));
await step(4000);
await shot('02-playing');
await page.keyboard.press('Tab');
await step(2500);
await shot('03-settings');
await page.click('.tab >> nth=2');
await step(2000);
await shot('04-settings-fx');
await page.click('.tab >> nth=3');
await step(2000);
await shot('05-settings-color');
await page.keyboard.press('Tab');
await page.keyboard.press('KeyL');
await step(2500);
await shot('06-playlist');
await page.keyboard.press('KeyL');
await page.keyboard.press('KeyG');
await step(2500);
await shot('07-scenes');
await page.keyboard.press('KeyG');
await page.keyboard.press('KeyX');
await step(1500);
await shot('08-export');
await page.keyboard.press('Escape');
await page.keyboard.press('KeyI');
await page.evaluate(() => window.__app.setScene('blackhole'));
await step(6000);
await shot('09-blackhole-hud');
fs.writeFileSync(`${out}/console.log`, logs.join('\n'));
await browser.close();
await server.close();
