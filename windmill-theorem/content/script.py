_MARK = re.compile(r"\[\[(.+?)\|\|(.+?)\]\]")


def shown(text):
    """Text for subtitles and transcripts."""
    return _MARK.sub(lambda m: m.group(1), text)


def spoken(text):
    """Text for the speech engine."""
    return _MARK.sub(lambda m: m.group(2), text)


_ZH_SPLIT = re.compile(r"(?<=[。！？；])")


def _split_zh(text):
    """Split after 。！？； but never inside [[shown||spoken]] markup."""
    out, start, i = [], 0, 0
    while i < len(text):
        if text.startswith("[[", i):
            j = text.find("]]", i)
            i = len(text) if j < 0 else j + 2
            continue
        if text[i] in "。！？；":
            out.append(text[start:i + 1])
            start = i + 1
        i += 1
    out.append(text[start:])
    return out


def sentences(line, lang):
    """List of (raw_text, gloss) sentences of a line in one language."""
    if lang == "zh":
        if not line.zh:
            return []
        parts = [s for s in _split_zh(line.zh) if s.strip()]
        return [(s.strip(), None) for s in parts]
    return [(s, g) for s, g in (line.en or [])]


def lines_for(lang):
    return [ln for ln in SCRIPT if (ln.zh if lang == "zh" else ln.en)]
