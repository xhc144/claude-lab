#!/usr/bin/env node
// Bundle the app into ONE self-contained HTML file: dist/tensora.html.
// Browsers refuse to load ES modules from file://, so the source version needs a web server; the
// bundle inlines the CSS and every module (each wrapped in its own function scope) into a classic
// <script>, so it can be downloaded and opened by double-clicking, fully offline.
//
//   node scripts/build.mjs            (npm run build)
//   node scripts/build.mjs --check    fail if the committed dist/ file is stale (part of npm run lint)
//
// Zero dependencies. Supports exactly the module syntax this codebase uses:
//   import { a, b as c } from './x.js';   import x from './x.js';
//   export function|class|const|let NAME …;   export default …;

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const ENTRY = join(ROOT, 'src/main.js');
const OUT = join(ROOT, 'dist/tensora.html');

const IMPORT_RE = /^import\s+([^;'"]*?)\s+from\s+['"](\.{1,2}\/[^'"]+)['"];?[ \t]*$/gm;

const modules = new Map(); // path -> { id, code, deps }
const order = [];

function load(file, stack = []) {
  if (modules.has(file)) return;
  if (stack.includes(file)) throw new Error(`circular import: ${[...stack, file].map((f) => relative(ROOT, f)).join(' -> ')}`);
  const src = readFileSync(file, 'utf8');
  const id = relative(ROOT, file).replace(/\\/g, '/');
  const deps = [];
  for (const m of src.matchAll(IMPORT_RE)) deps.push(resolve(dirname(file), m[2]));
  for (const d of deps) load(d, [...stack, file]);
  modules.set(file, { id, src });
  order.push(file);
}

function transform(file) {
  const { id, src } = modules.get(file);
  const exportsList = [];
  let hasDefault = false;
  let code = src.replace(IMPORT_RE, (_, clause, spec) => {
    const dep = JSON.stringify(modules.get(resolve(dirname(file), spec)).id);
    const parts = [];
    const named = /\{([^}]*)\}/.exec(clause);
    const def = /^\s*([A-Za-z_$][\w$]*)\s*(,|$)/.exec(clause);
    if (def) parts.push(`const ${def[1]} = __m[${dep}].default;`);
    if (named) {
      const fields = named[1].split(',').map((s) => s.trim()).filter(Boolean)
        .map((s) => { const [a, b] = s.split(/\s+as\s+/); return b ? `${a}: ${b}` : a; });
      parts.push(`const { ${fields.join(', ')} } = __m[${dep}];`);
    }
    return parts.join(' ');
  });
  code = code.replace(/^export\s+default\s+/m, () => { hasDefault = true; return 'const __default__ = '; });
  code = code.replace(/^export\s+((?:async\s+)?(?:function\*?|class|const|let|var))\s+([A-Za-z_$][\w$]*)/gm, (_, kind, name) => {
    exportsList.push(name);
    return `${kind} ${name}`;
  });
  if (/^\s*(import|export)\s/m.test(code)) throw new Error(`${id}: unsupported import/export form left after transform`);
  const ret = [...exportsList, ...(hasDefault ? ['default: __default__'] : [])].join(', ');
  return `// ---- ${id}\n__m[${JSON.stringify(id)}] = (() => {\n"use strict";\n${code}\nreturn { ${ret} };\n})();\n`;
}

load(ENTRY);
let js = `(() => {\nconst __m = Object.create(null);\n${order.map(transform).join('\n')}\n})();\n`;
js = js.replace(/<\/script/gi, '<\\/script'); // never end the inline <script> early

const css = readFileSync(join(ROOT, 'css/app.css'), 'utf8');
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
let html = readFileSync(join(ROOT, 'index.html'), 'utf8');
const banner = `<!-- 星枢 Tensora v${pkg.version} — single-file build. Open directly in a browser (works offline).\n     Source: tensora/ in https://github.com/xhc144/claude-lab — generated by scripts/build.mjs, do not edit. -->`;
const swap = (from, to) => {
  if (!html.includes(from)) throw new Error(`index.html: cannot find ${from}`);
  html = html.replace(from, () => to);
};
swap('<link rel="stylesheet" href="css/app.css">', `<style>\n${css}</style>`);
swap('<script type="module" src="src/main.js"></script>', `<script>\n${js}</script>`);
html = html.replace('<!doctype html>', `<!doctype html>\n${banner}`);

if (process.argv.includes('--check')) {
  // used by `npm run lint`: the committed single-file build must match the current source
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
  if (current !== html) {
    console.error(`✗ ${relative(ROOT, OUT)} is out of date — run \`npm run build\` and commit it`);
    process.exit(1);
  }
  console.log(`✓ ${relative(ROOT, OUT)} is up to date`);
  process.exit(0);
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, html);
console.log(`✓ ${relative(ROOT, OUT)}  ${(html.length / 1024).toFixed(0)} KB, ${order.length} modules inlined`);
